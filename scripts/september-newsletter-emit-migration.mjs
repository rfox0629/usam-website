// Regenerates the September issue's seed migration from the section fixture.
//
//   node --no-warnings --import ./scripts/ts-loader.mjs \
//     scripts/september-newsletter-emit-migration.mjs
//
// The fixture (src/lib/communications/september-2026-sections.ts) is the single
// source for the issue's structured content. Editing the SQL by hand would let
// the two drift; run this instead. After the migration has been applied, the
// RECORD is the source of truth and this script stops being the way to change
// copy — Operations is.
import { writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = process.cwd();
const stamp = "20260917214500";
const { septemberSections, SEPTEMBER_PREHEADER, SEPTEMBER_SUBJECT } = await import(
  pathToFileURL(path.join(root, "src/lib/communications/september-2026-sections.ts")).href
);

const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
const sections = JSON.stringify(septemberSections, null, 2);

// Guard: the review-only mockup must never reach a migration.
if (/a woman joined us|first encounter of ministry/i.test(sections)) {
  throw new Error("the unapproved story mockup is in the section fixture");
}

for (const section of septemberSections) {
  if (section.type === "story" && (section.story || section.body)) {
    throw new Error(`story section "${section.key}" carries copy; permission is not verified`);
  }
}

const up = `-- September 2026 issue: the Operations record becomes the source of truth.
--
-- Until now the September issue rendered from a TypeScript module
-- (src/lib/communications/september-2026.ts) that render.ts selected by slug, so
-- its copy could only be changed by a developer and a deploy, and the record's
-- own body and sections were ignored. This migration moves the issue's content
-- onto the record and adds what a real review workflow needs:
--
--   * postal_address, so CAN-SPAM's physical address has a source at all. The
--     send-readiness check now blocks on it.
--   * template, so an issue names the renderer that draws it.
--   * communication_newsletter_revisions, so every edit is recoverable.
--
-- Version A is preserved twice over: the TypeScript module is untouched in the
-- repository, and the row as it stands right now is written into the revisions
-- table as revision 1 BEFORE anything is overwritten.
--
-- The featured testimony is deliberately absent. The sharing permission on
-- Planning Center form 1115723, submission 45980998 has not been verified, so
-- the story section is seeded hidden and carries no copy.
--
-- Generated by scripts/september-newsletter-emit-migration.mjs. Do not hand-edit.

alter table public.communication_newsletters
  add column if not exists postal_address text,
  add column if not exists template text;

comment on column public.communication_newsletters.postal_address is
  'CAN-SPAM physical mailing address. Null renders nothing and blocks sending.';
comment on column public.communication_newsletters.template is
  'Renderer for this issue: ''sections'' (default) or ''ecosystem''.';

create table if not exists public.communication_newsletter_revisions (
  id uuid primary key default gen_random_uuid(),
  newsletter_id uuid not null references public.communication_newsletters (id) on delete cascade,
  revision integer not null,
  snapshot jsonb not null,
  summary text,
  created_at timestamptz not null default now(),
  created_by_email text not null,
  unique (newsletter_id, revision)
);

create index if not exists communication_newsletter_revisions_newsletter_idx
  on public.communication_newsletter_revisions (newsletter_id, revision desc);

alter table public.communication_newsletter_revisions enable row level security;

-- Service role only, matching the rest of the communications tables: every
-- reader and writer goes through the Operations server actions.
drop policy if exists communication_newsletter_revisions_service_role
  on public.communication_newsletter_revisions;
create policy communication_newsletter_revisions_service_role
  on public.communication_newsletter_revisions
  for all to service_role using (true) with check (true);

-- Revision 1: the row exactly as it is today, before this migration edits it.
insert into public.communication_newsletter_revisions
  (newsletter_id, revision, snapshot, summary, created_by_email)
select
  n.id,
  1,
  to_jsonb(n),
  'Version A, captured before the September issue moved onto its record.',
  'migration:${stamp}'
from public.communication_newsletters n
where n.slug = 'q2-q3-2026-field-update'
on conflict (newsletter_id, revision) do nothing;

-- The issue's content, as structured sections.
update public.communication_newsletters
set
  template = 'ecosystem',
  subject = ${q(SEPTEMBER_SUBJECT)},
  title = ${q(SEPTEMBER_SUBJECT)},
  preheader = ${q(SEPTEMBER_PREHEADER)},
  summary = ${q(SEPTEMBER_PREHEADER)},
  sections = ${q(sections)}::jsonb,
  updated_at = now(),
  updated_by_email = 'migration:${stamp}'
where slug = 'q2-q3-2026-field-update';

-- Deliberately untouched: status, planned_send_at, ready_at, last_test_sent_at,
-- approved_at, approved_by_email, sent_at. The passed September 15 date is left
-- as it is rather than replaced with an invented one, the issue stays
-- unapproved, and nothing here enables a send.
`;

const down = `-- Rollback: put the September issue back the way it was.
--
-- Restores the row from revision 1 (Version A) if it is there, then drops what
-- this migration added. Revision history goes with the table, so export it
-- first if any of it matters.
--
-- Generated by scripts/september-newsletter-emit-migration.mjs. Do not hand-edit.

update public.communication_newsletters n
set
  title = r.snapshot ->> 'title',
  subject = r.snapshot ->> 'subject',
  preheader = r.snapshot ->> 'preheader',
  summary = r.snapshot ->> 'summary',
  sections = coalesce(r.snapshot -> 'sections', '[]'::jsonb),
  updated_at = now(),
  updated_by_email = 'rollback:${stamp}'
from public.communication_newsletter_revisions r
where r.newsletter_id = n.id
  and r.revision = 1
  and n.slug = 'q2-q3-2026-field-update';

drop table if exists public.communication_newsletter_revisions;

alter table public.communication_newsletters
  drop column if exists template,
  drop column if exists postal_address;
`;

const base = path.join(root, "supabase", "migrations", `${stamp}_newsletter_record_source_of_truth`);
await writeFile(`${base}.sql`, up, "utf8");
await writeFile(`${base}_rollback.sql`, down, "utf8");
console.log(`written: ${septemberSections.length} sections, ${sections.length} bytes of jsonb`);
